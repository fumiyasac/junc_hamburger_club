  static List<Burger> getPopularBurgers() {
    return burgers.where((b) => b.isPopular).toList();
  }

  static List<Burger> getBurgersByCategory(String categoryId) {
    return burgers.where((b) => b.categoryId == categoryId).toList();
  }

  static List<Burger> searchBurgers(String query) {
    final q = query.toLowerCase();
    return burgers.where((b) {
      return b.name.toLowerCase().contains(q) ||
          b.description.toLowerCase().contains(q) ||
          b.tags.any((t) => t.toLowerCase().contains(q));
    }).toList();
  }

  static Burger? getBurgerById(String id) {
    try {
      return burgers.firstWhere((b) => b.id == id);
    } catch (_) {
      return null;
    }
  }
